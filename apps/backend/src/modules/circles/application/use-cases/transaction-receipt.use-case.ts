import { Inject, Injectable } from '@nestjs/common';

import { type Principal } from '../../../../shared/application/ports/access-token-verifier.port';
import { CLOCK, type ClockPort } from '../../../../shared/application/ports/clock.port';
import { type Money } from '../../../../shared/domain/value-objects/money';
import { type TransactionDetail, type TransactionType } from '../ports/payments-query.port';
import { GetTransactionUseCase } from './get-transaction.use-case';

export const RECEIPT_DETAILS = Symbol('RECEIPT_DETAILS');
export const RECEIPT_SETTINGS = Symbol('RECEIPT_SETTINGS');
export const RECEIPT_RENDERER = Symbol('RECEIPT_RENDERER');

/** El comprobante ya armado y traducido; el adaptador solo lo dibuja. */
export interface ReceiptDocument {
  title: string;
  amountLabel: string;
  amount: string;
  rows: [label: string, value: string][];
  footer: string;
}

export interface ReceiptRendererPort {
  /** El archivo listo para descargar (PDF). */
  render(document: ReceiptDocument): Buffer;
}

export interface ReceiptSettings {
  readonly timeZone: string;
}

/** Datos del comprobante que no están en el detalle del movimiento. */
export interface ReceiptDetailsPort {
  /**
   * Con qué se pagó o a dónde se cobró, enmascarado ("Visa •••• 4242", "BCP •••• 1234"), o
   * `null` si no quedó registrado.
   */
  methodOf(userId: string, detail: TransactionDetail): Promise<string | null>;
}

export const RECEIPT_LANGUAGES = ['es', 'en'] as const;
export type ReceiptLanguage = (typeof RECEIPT_LANGUAGES)[number];

const TEXT = {
  es: {
    title: { payment: 'Comprobante de pago', payout: 'Comprobante de cobro' },
    concept: {
      installment: 'Cuota de {period}',
      debt_settlement: 'Pago de deuda pendiente',
      payout: 'Pozo de {period}',
      refund: 'Devolución de cuotas',
    },
    amount: 'Monto',
    conceptLabel: 'Concepto',
    circle: 'Junta',
    circleValue: 'Pozo de {payout} · turno {position}',
    deductions: 'Descontado del pozo',
    date: 'Fecha',
    method: { payment: 'Método de pago', payout: 'Cuenta de cobro' },
    noMethod: 'No registrado',
    operation: 'N.º de operación',
    generated: 'Generado por Ayni el {date}.',
    locale: 'es-PE',
  },
  en: {
    title: { payment: 'Payment receipt', payout: 'Payout receipt' },
    concept: {
      installment: '{period} installment',
      debt_settlement: 'Outstanding debt payment',
      payout: '{period} payout',
      refund: 'Installment refund',
    },
    amount: 'Amount',
    conceptLabel: 'Concept',
    circle: 'Circle',
    circleValue: '{payout} pot · slot {position}',
    deductions: 'Deducted from the pot',
    date: 'Date',
    method: { payment: 'Payment method', payout: 'Payout account' },
    noMethod: 'Not recorded',
    operation: 'Operation number',
    generated: 'Generated by Ayni on {date}.',
    locale: 'en-US',
  },
} as const;

const fill = (template: string, values: Record<string, string>): string =>
  template.replace(/\{(\w+)\}/g, (_, key: string) => values[key] ?? '');

/**
 * `GET /v1/me/transactions/:id/receipt` (COPAYNI-80): el comprobante en PDF de un pago o cobro del
 * usuario. Uno ajeno responde 404 (el detalle ya lo valida). Solo datos enmascarados: nunca el
 * número de la tarjeta, de la cuenta ni del celular.
 */
@Injectable()
export class GetTransactionReceiptUseCase {
  constructor(
    @Inject(GetTransactionUseCase) private readonly getTransaction: GetTransactionUseCase,
    @Inject(RECEIPT_DETAILS) private readonly details: ReceiptDetailsPort,
    @Inject(RECEIPT_SETTINGS) private readonly settings: ReceiptSettings,
    @Inject(CLOCK) private readonly clock: ClockPort,
    @Inject(RECEIPT_RENDERER) private readonly renderer: ReceiptRendererPort,
  ) {}

  async execute(
    principal: Principal,
    query: { type: TransactionType; id: string; language?: string },
  ): Promise<{ filename: string; pdf: Buffer }> {
    const detail = await this.getTransaction.execute(principal, query);
    const method = await this.details.methodOf(principal.userId, detail);
    const language: ReceiptLanguage = query.language === 'en' ? 'en' : 'es';
    const text = TEXT[language];
    const money = (value: Money): string =>
      new Intl.NumberFormat(text.locale, { style: 'currency', currency: value.currency }).format(
        value.amount / 100,
      );
    const dateTime = (value: Date): string =>
      new Intl.DateTimeFormat(text.locale, {
        dateStyle: 'medium',
        timeStyle: 'short',
        timeZone: this.settings.timeZone,
      }).format(value);
    const period = detail.period
      ? new Intl.DateTimeFormat(text.locale, {
          month: 'long',
          year: 'numeric',
          timeZone: 'UTC',
        }).format(new Date(`${detail.period.toString()}-15T00:00:00Z`))
      : '';

    const rows: [string, string][] = [
      [text.conceptLabel, fill(text.concept[detail.kind], { period })],
      [
        text.circle,
        fill(text.circleValue, {
          payout: money(detail.circlePayout),
          position: String(detail.position),
        }),
      ],
      [text.date, dateTime(detail.occurredAt)],
      [text.method[detail.type], method ?? text.noMethod],
      [text.operation, detail.id],
    ];
    const deducted = detail.circlePayout.amount - detail.amount.amount;
    if (detail.kind === 'payout' && deducted > 0) {
      rows.splice(2, 0, [
        text.deductions,
        money({ amount: deducted, currency: detail.amount.currency } as Money),
      ]);
    }

    const pdf = this.renderer.render({
      title: text.title[detail.type],
      amountLabel: text.amount,
      amount: money(detail.amount),
      rows,
      footer: fill(text.generated, { date: dateTime(this.clock.now()) }),
    });
    return { filename: `ayni-comprobante-${detail.id.slice(0, 8)}.pdf`, pdf };
  }
}
